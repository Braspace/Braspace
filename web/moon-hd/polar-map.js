// LUA3D · polar map: the south polar cap of Joel's Moon HD (scene.ts cap shader, LOLA relief) seen from straight
// above (nadir, grid north up), with every catalogue site as a ship/rocket you click, tap or press Enter on.
// Zoom +/− buttons (44 px), mouse wheel, pinch, drag to pan, "centre on the site". One component for every screen
// (contract /orq/lua3d/CONTRATO.md): Explore and Compare (card L1), Replan/Debrief/Evidence (L3) consume it.
//
// Engine: core/terrain.js (mountTerrain) keeps the projection (south polar stereographic, polar-math.ts), the
// free area between the panels, the crater names and the 2D LOLA 400 m hillshade fallback; with hardware WebGL 2
// the relief is the Moon HD cap (moon-hd/stereo-relief.ts: same LOLA grids and fragment shading as the 3D
// viewer, one renderer). Without the region heights at all, the illustrative poster (poster-fallback.ts) is shown
// with the ships still clickable on top (stereographic layout, CSS zoom). Nothing here changes a number.
// Source of truth: this .ts file. polar-map.js is generated by `npm --prefix web run build:ts`.
import { latLonToStereo } from "./polar-math.js";
// ---------------------------------------------------------------- pure helpers (node --test)
/** Visible span limits (metres across the short side of the free area): 4 km out past the whole 400 m LOLA region (the engine clamps to the grid). */
export const MIN_SPAN = 4000, MAX_SPAN = 600000, ZOOM_STEP = 1.4;
export const clampSpan = (span, max = MAX_SPAN) => Math.min(max, Math.max(MIN_SPAN, Number.isFinite(span) ? span : max));
/** New span after one zoom step: dir > 0 zooms in (smaller span), dir < 0 zooms out. */
export const zoomSpan = (span, dir, step = ZOOM_STEP, max = MAX_SPAN) => clampSpan(dir > 0 ? span / step : dir < 0 ? span * step : span, max);
export const atMinZoom = (span, max = MAX_SPAN) => clampSpan(span, max) >= max;
export const atMaxZoom = (span) => clampSpan(span) <= MIN_SPAN;
/** Stereographic metres of a site: its own x/y when given, else lat/lon through polar-math (south pole, PDS). */
export function siteStereo(s) {
    if (Number.isFinite(s.x) && Number.isFinite(s.y))
        return [s.x, s.y];
    return latLonToStereo(s.lat, s.lon);
}
/** Poster fallback: places the ships in a W×H box with the same orientation as the map (grid north up), with margin. */
export function posterLayout(sites, W, H, pad = 56) {
    const pts = sites.map(s => [s.id, ...siteStereo(s)]).filter(p => Number.isFinite(p[1]) && Number.isFinite(p[2]));
    const out = {};
    if (!pts.length || !(W > 0) || !(H > 0))
        return out;
    const xs = pts.map(p => p[1]), ys = pts.map(p => p[2]);
    const cx = (Math.min(...xs) + Math.max(...xs)) / 2, cy = (Math.min(...ys) + Math.max(...ys)) / 2;
    const span = Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys), 1);
    const k = Math.max(1e-9, Math.min(W - 2 * pad, H - 2 * pad)) / span;
    for (const [id, x, y] of pts)
        out[id] = [W / 2 + (x - cx) * k, H / 2 - (y - cy) * k];
    return out;
}
/** Same effect everywhere: the onSelect callback and a bubbling CustomEvent "polarmap:select" {detail:{id}}. */
export function emitSelect(target, id, onSelect) {
    onSelect?.(id);
    target.dispatchEvent(new CustomEvent("polarmap:select", { detail: { id }, bubbles: true }));
}
/** Which background a browser gets: hardware WebGL 2 → Moon HD cap; no WebGL → LOLA 2D hillshade; no heights → poster. */
export function pickMode({ webgl2, heights }) {
    return !heights ? "poster" : webgl2 ? "moonhd" : "lola-2d";
}
/** Overlay bounds when they are stereographic metres; anything else (unknown shape) is ignored. */
export function overlayBounds(b) {
    const o = b;
    return o && [o.x0, o.y0, o.x1, o.y1].every(Number.isFinite) && o.x1 > o.x0 && o.y1 > o.y0 ? o : null;
}
export const TEXTS = {
    pt: { zin: "Aproximar o mapa", zout: "Afastar o mapa", center: "Centralizar no local escolhido", ship: "{b} · {name} (nave do local)", map: "Lua 3D vista de cima, polo sul", poster: "Imagem ilustrativa: sem as alturas LOLA, as naves mostram a posição relativa dos locais." },
    en: { zin: "Zoom in on the map", zout: "Zoom out of the map", center: "Centre on the chosen site", ship: "{b} · {name} (site ship)", map: "3D Moon seen from above, south pole", poster: "Illustrative image: without the LOLA heights the ships show the sites' relative positions." },
};
const fill = (s, v) => s.replace(/\{(\w+)\}/g, (_, k) => v[k] ?? "");
/** Rocket/lander glyph (24×24, stroke = currentColor). */
export const SHIP_SVG = '<svg class="pm-ship-ico" viewBox="0 0 24 24" aria-hidden="true" focusable="false"><path d="M12 2.5c2.6 2.2 3.9 5.4 3.9 9.2v4.1H8.1v-4.1c0-3.8 1.3-7 3.9-9.2z" fill="currentColor" fill-opacity=".18" stroke="currentColor" stroke-width="1.6" stroke-linejoin="round"/><circle cx="12" cy="9.6" r="1.7" fill="none" stroke="currentColor" stroke-width="1.5"/><path d="M8.1 12.6 5 15.8v2.4l3.1-1.3M15.9 12.6l3.1 3.2v2.4l-3.1-1.3M10.2 15.8l-.6 3.4M13.8 15.8l.6 3.4M12 17.6v3.2" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round"/></svg>';
// ---------------------------------------------------------------- DOM component
function ensureCss() {
    if (typeof document === "undefined" || document.querySelector("link[data-polar-map-css]"))
        return;
    const l = document.createElement("link");
    l.rel = "stylesheet";
    l.href = new URL("./polar-map.css", import.meta.url).href;
    l.dataset.polarMapCss = "";
    document.head.append(l);
}
export function mountPolarMap(container, opts) {
    ensureCss();
    const L = TEXTS[opts.lang || (String(document.documentElement.lang || "").toLowerCase().startsWith("pt") ? "pt" : "en")];
    container.classList.add("pm-map");
    container.dataset.polarMap = "pending";
    container.setAttribute("aria-label", L.map);
    let sel = opts.selectedId, overlay = opts.overlay || null, dead = false, mode = "pending";
    // Live arrays read by the engine on every draw (setSites/setLinks mutate them in place).
    const tsites = [], tlinks = [];
    const ships = new Map();
    const fillSites = (list) => {
        ships.clear();
        tsites.length = 0;
        for (const s of list) {
            const [x, y] = siteStereo(s);
            if (!Number.isFinite(x) || !Number.isFinite(y))
                continue;
            ships.set(s.id, s);
            tsites.push({ id: s.id, n: s.badge, name: s.label, stereo_x_m: x, stereo_y_m: y, lat: s.lat, lon: s.lon });
        }
    };
    const fillLinks = (list = []) => { tlinks.length = 0; for (const k of list)
        if (k.from !== k.to)
            tlinks.push([k.from, k.to]); };
    fillSites(opts.sites || []);
    fillLinks(opts.links);
    // Controls: + / − / centre, 44 px, labelled. They live in the map container (not a page panel).
    const ctl = document.createElement("div");
    ctl.className = "pm-controls";
    ctl.setAttribute("role", "group");
    ctl.dataset.noMoonDrag = "";
    const mk = (cls, text, label, fn) => { const b = document.createElement("button"); b.type = "button"; b.className = "pm-btn " + cls; b.textContent = text; b.setAttribute("aria-label", label); b.title = label; b.onclick = fn; ctl.append(b); return b; };
    const bIn = mk("pm-in", "+", L.zin, () => api.zoomIn()), bOut = mk("pm-out", "−", L.zout, () => api.zoomOut());
    mk("pm-center", "◎", L.center, () => api.center());
    if (opts.controls === "center") {
        bIn.hidden = bOut.hidden = true;
        ctl.dataset.controls = "center";
    }
    const ovImg = document.createElement("img");
    ovImg.className = "pm-overlay";
    ovImg.alt = "";
    ovImg.setAttribute("aria-hidden", "true");
    ovImg.hidden = true;
    ovImg.draggable = false;
    let engine = null;
    // ---- ships: the engine rebuilds its markers on every draw; each one is dressed as a ship here.
    function dress() {
        if (dead)
            return;
        for (const b of container.querySelectorAll(".mp-marker")) {
            const s = ships.get(b.dataset.site || "");
            if (!s || b.classList.contains("pm-ship"))
                continue;
            b.classList.add("pm-ship");
            if (s.state)
                b.dataset.state = s.state;
            const txt = b.firstChild;
            const badge = document.createElement("b");
            badge.className = "pm-badge";
            badge.textContent = s.badge;
            if (txt && txt.nodeType === 3)
                txt.remove();
            b.insertAdjacentHTML("afterbegin", SHIP_SVG);
            b.insertBefore(badge, b.children[1] || null);
            b.setAttribute("aria-label", fill(L.ship, { b: s.badge, name: s.label }));
            b.onclick = () => api.select(s.id, true);
        }
        placeOverlay();
        const span = engine?.view.span ?? MAX_SPAN;
        bIn.disabled = atMaxZoom(span);
        bOut.disabled = atMinZoom(span);
        container.dataset.span = String(Math.round(span));
        opts.onView?.();
    }
    function placeOverlay() {
        const b = overlayBounds(overlay?.bounds);
        if (!overlay || !b || !engine || !engine.ready) {
            ovImg.hidden = true;
            return;
        }
        const [l, t] = engine.toPx(b.x0, b.y1), [r, btm] = engine.toPx(b.x1, b.y0);
        if (ovImg.getAttribute("src") !== overlay.url)
            ovImg.src = overlay.url;
        Object.assign(ovImg.style, { left: l + "px", top: t + "px", width: (r - l) + "px", height: (btm - t) + "px", opacity: String(overlay.opacity ?? .62) });
        ovImg.hidden = false;
    }
    const redraw = () => { if (engine)
        engine.redraw();
    else if (mode === "poster")
        layoutPoster(); };
    // ---- pan (drag), wheel and pinch on the empty map (never on a ship, a button or a page panel)
    const pts = new Map();
    let dragged = 0, pinch0 = 0, span0 = 0, posterZoom = 1, posterPan = [0, 0];
    const onMap = (e) => { const el = e.target; return !!el && container.contains(el) && !el.closest(".pm-controls, .mp-marker, .pm-ship, a, input, select, textarea"); };
    const setSpan = (span) => { if (engine) {
        engine.view.span = zoomSpan(span, 0);
        engine.redraw();
    } };
    function panBy(dx, dy) {
        if (engine && engine.ready) {
            const m = engine.mpp;
            engine.view.cx -= dx * m;
            engine.view.cy += dy * m;
            engine.redraw();
        }
        else if (mode === "poster") {
            posterPan = [posterPan[0] + dx, posterPan[1] + dy];
            layoutPoster();
        }
    }
    const down = (e) => {
        if (!onMap(e) || e.button > 0)
            return;
        pts.set(e.pointerId, [e.clientX, e.clientY]);
        dragged = 0;
        if (pts.size === 2) {
            const [a, b] = [...pts.values()];
            pinch0 = Math.hypot(a[0] - b[0], a[1] - b[1]);
            span0 = engine?.view.span ?? 0;
        }
    };
    const move = (e) => {
        const p = pts.get(e.pointerId);
        if (!p)
            return;
        const dx = e.clientX - p[0], dy = e.clientY - p[1];
        pts.set(e.pointerId, [e.clientX, e.clientY]);
        if (pts.size === 2 && pinch0 > 0) {
            const [a, b] = [...pts.values()], d = Math.hypot(a[0] - b[0], a[1] - b[1]);
            dragged += 10;
            if (engine)
                setSpan(span0 * pinch0 / Math.max(1, d));
            else if (mode === "poster") {
                posterZoom = Math.min(4, Math.max(1, posterZoom * d / pinch0));
                pinch0 = d;
                layoutPoster();
            }
            return;
        }
        dragged += Math.abs(dx) + Math.abs(dy);
        if (dragged > 4) {
            container.classList.add("is-panning");
            panBy(dx, dy);
        }
    };
    const up = (e) => { pts.delete(e.pointerId); if (pts.size < 2)
        pinch0 = 0; if (!pts.size)
        container.classList.remove("is-panning"); };
    // A drag must not end as a click (Explore creates a point on click).
    const click = (e) => { if (dragged > 4) {
        e.stopPropagation();
        e.preventDefault();
        dragged = 0;
    } };
    const wheel = (e) => {
        if (!onMap(e))
            return;
        e.preventDefault();
        const dir = e.deltaY < 0 ? 1 : -1;
        if (engine)
            setSpan(zoomSpan(engine.view.span, dir, 1.15));
        else if (mode === "poster") {
            posterZoom = Math.min(4, Math.max(1, posterZoom * (dir > 0 ? 1.15 : 1 / 1.15)));
            layoutPoster();
        }
    };
    container.addEventListener("pointerdown", down);
    addEventListener("pointermove", move);
    addEventListener("pointerup", up);
    addEventListener("pointercancel", up);
    container.addEventListener("click", click, true);
    container.addEventListener("wheel", wheel, { passive: false });
    container.style.touchAction = "none";
    // ---- poster fallback (no LOLA heights): illustrative image + ships at their relative stereographic positions
    let posterLayer = null, posterDispose = null;
    function layoutPoster() {
        if (!posterLayer)
            return;
        const W = container.clientWidth || innerWidth, H = container.clientHeight || innerHeight;
        const pos = posterLayout([...ships.values()], W, H);
        posterLayer.style.transform = `translate(${posterPan[0]}px,${posterPan[1]}px) scale(${posterZoom})`;
        posterLayer.replaceChildren(...[...ships.values()].filter(s => pos[s.id]).map(s => {
            const b = document.createElement("button");
            b.type = "button";
            b.className = "mp-marker pm-ship";
            b.dataset.site = s.id;
            if (s.state)
                b.dataset.state = s.state;
            b.setAttribute("aria-pressed", String(s.id === sel));
            b.setAttribute("aria-label", fill(L.ship, { b: s.badge, name: s.label }));
            b.insertAdjacentHTML("afterbegin", SHIP_SVG);
            const bd = document.createElement("b");
            bd.className = "pm-badge";
            bd.textContent = s.badge;
            b.append(bd);
            const lab = document.createElement("span");
            lab.className = "mp-marker-label";
            lab.textContent = s.label;
            b.append(lab);
            Object.assign(b.style, { left: pos[s.id][0] + "px", top: pos[s.id][1] + "px", transform: `scale(${1 / posterZoom})` });
            b.onclick = () => api.select(s.id, true);
            return b;
        }));
        bIn.disabled = posterZoom >= 4;
        bOut.disabled = posterZoom <= 1;
    }
    async function poster() {
        mode = "poster";
        container.dataset.polarMap = "poster";
        container.replaceChildren();
        Object.assign(container.style, { position: container.style.position || "fixed", inset: "0", overflow: "hidden" });
        try {
            const P = await import("./poster-fallback.js");
            const p = P.mountMoonPoster(container, { view: "pole", lang: L === TEXTS.pt ? "pt" : "en" });
            posterDispose = () => p.dispose();
        }
        catch { /* the ships still work */ }
        const note = document.createElement("p");
        note.className = "pm-note";
        note.textContent = L.poster;
        container.append(note);
        posterLayer = document.createElement("div");
        posterLayer.className = "pm-poster-ships";
        container.append(posterLayer, ctl);
        layoutPoster();
        addEventListener("resize", layoutPoster);
        return null;
    }
    const ready = import("../moonproof/core/terrain.js").then(T => T.mountTerrain(container, { sites: tsites, selected: sel ?? null, labels: opts.labels !== false, progressive: opts.progressive !== false,
        links: tlinks, minFeatureKm: 5, onUnavailable: () => { if (!dead) {
            engine = null;
            void poster();
        } }, onSelect: (id) => api.select(id, true), onDraw: dress }))
        .then((eng) => {
        if (dead)
            return null;
        engine = eng;
        const cv = container.querySelector("canvas");
        container.insertBefore(ovImg, cv ? cv.nextSibling : container.firstChild);
        container.append(ctl);
        const sync = () => { mode = container.dataset.relief === "moonhd" ? "moonhd" : "lola-2d"; container.dataset.polarMap = mode; };
        sync();
        new MutationObserver(sync).observe(container, { attributes: true, attributeFilter: ["data-relief"] });
        if (sel)
            engine.select(sel);
        else
            engine.redraw();
        return engine;
    })
        .catch(() => dead ? null : poster());
    const api = {
        get mode() { return mode; }, get selectedId() { return sel; }, ready,
        setSites(s) { fillSites(s || []); redraw(); },
        setLinks(l) { fillLinks(l); redraw(); },
        select(id, user = false) {
            if (!ships.has(id))
                return;
            sel = id;
            if (engine)
                engine.select(id);
            else
                redraw();
            if (user)
                emitSelect(container, id, opts.onSelect);
        },
        setOverlay(o) { overlay = o; placeOverlay(); },
        zoomIn() { if (engine)
            setSpan(zoomSpan(engine.view.span, 1));
        else if (mode === "poster") {
            posterZoom = Math.min(4, posterZoom * ZOOM_STEP);
            layoutPoster();
        } },
        zoomOut() { if (engine)
            setSpan(zoomSpan(engine.view.span, -1));
        else if (mode === "poster") {
            posterZoom = Math.max(1, posterZoom / ZOOM_STEP);
            if (posterZoom === 1)
                posterPan = [0, 0];
            layoutPoster();
        } },
        center(id) {
            const s = ships.get(id || sel || "");
            if (!s)
                return;
            if (engine) {
                const [x, y] = siteStereo(s);
                engine.view.cx = x;
                engine.view.cy = y;
                engine.redraw();
            }
            else if (mode === "poster") {
                posterPan = [0, 0];
                layoutPoster();
            }
        },
        destroy() {
            dead = true;
            removeEventListener("pointermove", move);
            removeEventListener("pointerup", up);
            removeEventListener("pointercancel", up);
            removeEventListener("resize", layoutPoster);
            container.removeEventListener("pointerdown", down);
            container.removeEventListener("click", click, true);
            container.removeEventListener("wheel", wheel);
            posterDispose?.();
            ctl.remove();
            ovImg.remove();
            container.classList.remove("pm-map");
        },
    };
    return api;
}
