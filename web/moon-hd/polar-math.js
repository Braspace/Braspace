// South polar stereographic grid -> local 3D frame at the pole. Pure functions (node --test).
// The same expressions are repeated in GLSL in app.js; polar-math.test.mjs pins them against web/lab/coords.js.
//
// Stereographic (PDS, spherical, true scale at the pole): x = rho sin(lon), y = rho cos(lon), rho = 2R tan((lat+90°)/2).
// Local frame, metres, origin on the reference sphere at the south pole:
//   a along stereographic +x (toward 90°E), b along +y (toward 0°E), c outward ("up" at the pole).
// Written so that no term subtracts two numbers of the size of the lunar radius.
// Source of truth: this .ts file. polar-math.js is generated by `npm --prefix web run build:ts`.
export const R_REF = 1737400;
/** South of this latitude the viewer draws the LOLA cap instead of the global mosaic relief. */
export const CAP_LAT = -80.35;
/** Heights (m above the sphere) at the two ends of the altitude colour ramp. */
export const ALTITUDE_RANGE = [-7000, 8000];
/** Stereographic (x, y) metres and height h (m above the sphere) -> local [a, b, c] metres. */
export function stereoToLocal(x, y, h, R = R_REF) {
    const X = x / (2 * R), Y = y / (2 * R), s = X * X + Y * Y, k = 1 / (1 + s);
    return [(R + h) * 2 * X * k, (R + h) * 2 * Y * k, (h * (1 - s) - 2 * R * s) * k];
}
/** Local [a, b, c] -> { x, y } stereographic metres and altitude (m above the sphere). */
export function localToStereo([a, b, c], R = R_REF) {
    const cz = c + R, r = Math.hypot(a, b, cz), k = 2 * R / (r + cz);
    return { x: a * k, y: b * k, altitude: (a * a + b * b + c * c + 2 * c * R) / (r + R) };
}
/** Polar scene (km): +X toward 0°E, +Y up, +Z toward 90°E. */
export const localToScene = ([a, b, c]) => [b / 1000, c / 1000, a / 1000];
export function latLonToStereo(lat, lon, R = R_REF) {
    const rho = 2 * R * Math.tan(((lat + 90) * Math.PI / 180) / 2), lo = lon * Math.PI / 180;
    return [rho * Math.sin(lo), rho * Math.cos(lo)];
}
/** Grid helper for a braspace.terrain-grid.v1 raster (row 0 = min y, values at pixel centres). */
export function makeGrid(meta, dn) {
    if (dn.length !== meta.nx * meta.ny)
        throw new Error("terrain grid: unexpected length");
    const half = meta.nx * meta.spacing_m / 2;
    if (Math.abs(meta.origin_x_m - (-half + meta.spacing_m / 2)) > 1e-6 || meta.nx !== meta.ny || meta.origin_x_m !== meta.origin_y_m)
        throw new Error("terrain grid: not a centred square grid");
    return {
        nx: meta.nx, spacing: meta.spacing_m, half, scale: meta.scale_m, dn,
        contains: (x, y) => Math.abs(x) < half && Math.abs(y) < half,
        /** Nearest-pixel height in metres. */
        heightAt(x, y) {
            const i = Math.min(meta.nx - 1, Math.max(0, Math.round((x - meta.origin_x_m) / meta.spacing_m)));
            const j = Math.min(meta.ny - 1, Math.max(0, Math.round((y - meta.origin_y_m) / meta.spacing_m)));
            return dn[j * meta.nx + i] * meta.scale_m + (meta.offset_m || 0);
        },
    };
}
/** Bilinear height (m) at stereographic (x, y); same sampling as the GPU's linear filter. */
export function bilinearHeight(grid, x, y) {
    const fx = (x + grid.half) / grid.spacing - 0.5, fy = (y + grid.half) / grid.spacing - 0.5, n = grid.nx, d = grid.dn;
    const i = Math.max(0, Math.min(n - 2, Math.floor(fx))), j = Math.max(0, Math.min(n - 2, Math.floor(fy))), u = fx - i, v = fy - j;
    return ((d[j * n + i] * (1 - u) + d[j * n + i + 1] * u) * (1 - v) + (d[(j + 1) * n + i] * (1 - u) + d[(j + 1) * n + i + 1] * u) * v) * grid.scale;
}
/**
 * CPU reference of the fragment shader's shadow march (CAP_FRAGMENT in app.js, relief x1): smallest angle (rad) between
 * the ray toward the Sun and the terrain, from a point `mast` metres above the ground. Negative = Sun centre hidden.
 * With `wide` (the 320 m grid out to 80 S) it samples the same two-grid terrain as the shader.
 * `sun` is the unit Sun direction in the polar scene frame (x toward 0E, y up, z toward 90E).
 */
export function sunClearance(grid, x, y, mast, sun, wide = null, steps = 144, range = 260000, R = R_REF) {
    const smooth = (v) => { const u = Math.min(1, Math.max(0, v)); return u * u * (3 - 2 * u); };
    // Same blend as H() in the shader: native grid near the pole, the wide grid beyond it.
    const height = (px, py) => {
        if (!wide)
            return bilinearHeight(grid, px, py);
        const w = smooth((Math.max(Math.abs(px), Math.abs(py)) - (grid.half - 3000)) / 2400);
        return w >= 1 ? bilinearHeight(wide, px, py) : bilinearHeight(grid, px, py) * (1 - w) + bilinearHeight(wide, px, py) * w;
    };
    const limit = (wide || grid).half, reach = wide ? range : 2 * grid.half;
    const [a0, b0, c0] = stereoToLocal(x, y, height(x, y) + mast, R);
    let min = 1;
    for (let i = 1; i <= steps; i++) {
        const f = i / steps, t = 60 + reach * f * f;
        const q = localToStereo([a0 + sun[2] * t, b0 + sun[0] * t, c0 + sun[1] * t], R);
        if (Math.abs(q.x) > limit || Math.abs(q.y) > limit)
            break;
        min = Math.min(min, (q.altitude - height(q.x, q.y)) / t);
    }
    return min;
}
